const tables = { nl, en };

let lang: Lang = (() => {
  try {
    const saved = localStorage.getItem('df_lang');
    if (saved === 'nl' || saved === 'en') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith('nl') ? 'nl' : 'en';
})();

export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem('df_lang', l);
  } catch {
    /* ignore */
  }
}
document.documentElement.lang = lang;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = tables[lang][key] ?? nl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

/** Locale number: 6,5 in Dutch, 6.5 in English. */
export function num(n: number, digits = 1): string {
  const v = Number.isInteger(n) ? String(n) : n.toFixed(digits).replace(/\.?0+$/, '');
  return lang === 'nl' ? v.replace('.', ',') : v;
}
export function range([a, b]: [number, number], unit: string, digits = 1): string {
  return a === b ? `${num(a, digits)} ${unit}` : `${num(a, digits)}–${num(b, digits)} ${unit}`;
}
