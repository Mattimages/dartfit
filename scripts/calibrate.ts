/**
 * Fit the scan calibration from tape-measured hands and check gate G1.
 *
 *   npm run calibrate -- calibration.csv          # report only
 *   npm run calibrate -- calibration.csv --write  # also rewrite packages/engine/src/calibration.ts
 *
 * CSV columns: person,dim,app_mm,tape_mm
 *   dim is one of handLength, palmWidth, indexLength, middleLength, thumbIndexSpan.
 *   app_mm is what the hand screen showed; tape_mm is the same dimension with a tape measure
 *   (palmWidth on tape = across the four knuckles, not the landmark distance: the fit absorbs it).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fitLine, median, type Calibration, type DimKey } from '@dartfit/engine';
import { parseCsv } from '@dartfit/catalogue';

const [file, flag] = process.argv.slice(2);
if (!file) {
  console.error('usage: npm run calibrate -- calibration.csv [--write]');
  process.exit(1);
}
const rows = parseCsv(readFileSync(file, 'utf8'));
const dims: DimKey[] = ['handLength', 'palmWidth', 'indexLength', 'middleLength', 'thumbIndexSpan'];
const cal: Calibration = { calibrated: true, n: 0, dims: {} as Calibration['dims'] };
let gate = true;
for (const d of dims) {
  const pairs = rows.filter((r) => r.dim === d).map((r) => [Number(r.app_mm), Number(r.tape_mm)] as [number, number]);
  const people = new Set(rows.filter((r) => r.dim === d).map((r) => r.person)).size;
  if (pairs.length < 2) {
    cal.dims[d] = { a: 1, b: 0 };
    console.log(`${d}: not enough data, left uncorrected`);
    continue;
  }
  const line = fitLine(pairs);
  const before = median(pairs.map(([x, y]) => Math.abs(x - y)));
  const after = median(pairs.map(([x, y]) => Math.abs(line.a * x + line.b - y)));
  cal.dims[d] = { a: Number(line.a.toFixed(4)), b: Number(line.b.toFixed(2)) };
  cal.n = Math.max(cal.n, people);
  console.log(`${d}: n=${people} a=${line.a.toFixed(3)} b=${line.b.toFixed(1)} r²=${line.r2.toFixed(2)} median error ${before.toFixed(1)} → ${after.toFixed(1)} mm`);
  if ((d === 'handLength' || d === 'palmWidth') && (after > 3 || people < 10)) gate = false;
}
const tape = (d: DimKey) => rows.filter((r) => r.dim === d).map((r) => Number(r.tape_mm));
for (const d of ['handLength', 'palmWidth', 'middleLength'] as const) {
  const xs = tape(d);
  if (xs.length >= 10) {
    const m = median(xs);
    const sd = 1.4826 * median(xs.map((x) => Math.abs(x - m)));
    console.log(`  → set config.reference.${d} to { mu: ${m.toFixed(0)}, sigma: ${sd.toFixed(0)} } (tape scale)`);
  }
}
console.log(gate ? 'Gate G1: PASS' : 'Gate G1: not yet (needs ≥10 hands and ≤3 mm median error on hand length and knuckle width)');
if (flag === '--write') {
  const out = new URL('../packages/engine/src/calibration.ts', import.meta.url);
  writeFileSync(
    out,
    `/** Generated by scripts/calibrate.ts on ${new Date().toISOString().slice(0, 10)} from ${cal.n} hands. */\nimport type { Calibration } from './measure.js';\n\nexport const calibration: Calibration = ${JSON.stringify(cal, null, 2)};\n`,
  );
  console.log(`wrote ${out.pathname}`);
}
